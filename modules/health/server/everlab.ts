// Everlab's "Pathology Results Report": the one format its exports share (one PDF per panel a lab ran, whichever lab
// ran it), read from its lines of cells (pdf.ts). Its header names the lab ("Provider SNP / SNP") and the day the
// sample was collected; then each panel is a title ("SE-IRON STUDIES Collected 1 January 2026") and a table, either
// BIOMARKER | RESULT | UNITS | REFERENCE RANGE (numbers) or ITEM | VALUE (words, such as a screen's result, or the
// class of an allergy result printed above it). Every row becomes a Reading of its test (catalogue.ts); the range the
// lab printed is kept as evidence. Everything else on the page (the patient's name, the practitioner, the footers) is
// passed over.

import { testOf, testPrinted, unitOf, unknownKey } from "./catalogue.ts";
import type { PdfLine } from "./pdf.ts";
import type { Reading } from "./store.ts";

/** The labs Everlab names by their short names in a report's header. */
const LABS: Record<string, string> = {
  SNP: "Sullivan Nicolaides Pathology",
  MPS: "Melbourne Pathology",
  QML: "QML Pathology",
};

const MONTHS = ["january", "february", "march", "april", "may", "june", "july", "august", "september", "october", "november", "december"];

/** Whether pages are a Pathology Results Report. */
export function isPathologyReport(pages: readonly PdfLine[][]): boolean {
  return lineText(pages[0]?.[0] ?? []) === "Pathology Results Report";
}

/** "9 July 2024" as 2024-07-09, or null. */
export function dayOfPrinted(text: string): string | null {
  const match = /^(\d{1,2}) ([A-Za-z]+) (\d{4})$/.exec(text.trim());
  if (!match) return null;
  const month = MONTHS.indexOf(match[2].toLowerCase());
  if (month < 0) return null;
  return `${match[3]}-${String(month + 1).padStart(2, "0")}-${match[1].padStart(2, "0")}`;
}

/** Every result of a Pathology Results Report, its file `file` (from the archive's folder). Throws when it is not one. */
export function readPathologyReport(pages: readonly PdfLine[][], file: string): Reading[] {
  if (!isPathologyReport(pages)) throw new Error(`${file} is not a Pathology Results Report`);
  let lab: string | null = null;
  let collected: string | null = null;
  const rows: Reading[] = [];
  let table: "numbers" | "words" | null = null;
  let date: string | null = null;
  let note: string | null = null;
  pages.forEach((lines, index) => {
    const page = index + 1;
    for (const line of lines) {
      const cells = line.map(([text]) => text);
      const text = lineText(line);
      if (cells[0] === "Provider" || cells.includes("Provider")) {
        lab = labOf(cells.slice(cells.indexOf("Provider") + 1).join(" "));
        continue;
      }
      const header = /^Collected (\d{1,2} [A-Za-z]+ \d{4}) Reported/.exec(text);
      if (header) {
        collected = dayOfPrinted(header[1]);
        continue;
      }
      const panel = /^(.+?)\s+Collected (\d{1,2} [A-Za-z]+ \d{4})$/.exec(text);
      if (panel) {
        date = dayOfPrinted(panel[2]);
        table = null;
        note = null;
        continue;
      }
      if (cells[0] === "BIOMARKER") {
        table = "numbers";
        continue;
      }
      if (cells[0] === "ITEM" || text === "ITEM VALUE") {
        table = "words";
        continue;
      }
      if (/^(Confidential|Generated by|Page \d)/.test(text)) {
        table = null;
        continue;
      }
      if (table === null || cells.length < 2) continue;
      const day = date ?? collected;
      if (day === null) throw new Error(`${file}: a result before any collection date`);
      const where = `${file} p${page}`;
      if (table === "numbers") {
        rows.push(numberRow(cells, day, lab ?? "Unknown lab", where));
      } else if (cells[0] === "Site") {
        note = `Site: ${cells.slice(1).join(" ")}`;
      } else {
        rows.push({ ...wordsRow(cells, day, lab ?? "Unknown lab", where), note });
      }
    }
  });
  return mergeSameResult(rows);
}

/** "SNP / SNP" or "MPS / Melbourne Pathology" as the lab's name. */
function labOf(text: string): string {
  const [short, long] = text.split("/").map((part) => part.trim());
  if (long && long !== short) return long;
  return LABS[short] ?? short;
}

/** A row of a BIOMARKER table: the name, the result, then the unit and the printed range (either may be missing). */
function numberRow(cells: string[], date: string, lab: string, source: string): Reading {
  const [printed, result, ...rest] = cells;
  const range = rest.find(isRange) ?? null;
  const unit = rest.find((cell) => cell !== range) ?? null;
  const number = numberOf(result);
  return {
    test: testPrinted(printed)?.key ?? unknownKey(printed),
    date,
    value: number?.value ?? null,
    qualifier: number?.qualifier ?? null,
    text: number ? null : result,
    unit,
    printed: printed.replace(/:\s*$/, ""),
    labRange: range,
    lab,
    sources: [source],
    alsoAs: [],
    note: null,
  };
}

/** A row of an ITEM | VALUE table: the name and the result in words. */
function wordsRow(cells: string[], date: string, lab: string, source: string): Reading {
  const printed = cells[0];
  return {
    test: testPrinted(printed)?.key ?? unknownKey(printed),
    date,
    value: null,
    qualifier: null,
    text: cells.slice(1).join(" "),
    unit: null,
    printed: printed.replace(/:\s*$/, ""),
    labRange: null,
    lab,
    sources: [source],
    alsoAs: [],
    note: null,
  };
}

/** A printed range: "135-145", "0-0.9", "<1.7", ">59", "> 1.00". */
export function isRange(text: string): boolean {
  return /^[<>]\s?\d/.test(text) || /^\d+(\.\d+)?\s?-\s?\d+(\.\d+)?$/.test(text);
}

/** A printed result as a number, with its "<" or ">", or null for words. */
export function numberOf(text: string): { value: number; qualifier: "<" | ">" | null } | null {
  const match = /^([<>])?\s*(-?\d+(?:\.\d+)?)$/.exec(text.trim().replace(/,/g, ""));
  if (!match) return null;
  return { value: Number(match[2]), qualifier: (match[1] as "<" | ">" | undefined) ?? null };
}

/**
 * One reading for each test and day: a result printed again another way (in the test's other unit, or as an allergy
 * result's class beside its number) is kept as "also printed as" on the one in the test's own unit.
 */
export function mergeSameResult(rows: readonly Reading[]): Reading[] {
  const kept: Reading[] = [];
  for (const row of rows) {
    const same = kept.find((other) => other.test === row.test && other.date === row.date);
    if (!same || row.test.startsWith("unknown:")) {
      kept.push(row);
      continue;
    }
    const own = testOf(row.test)?.unit ?? null;
    const rowIsOwn = row.value !== null && unitOf(row.unit) === own;
    const sameIsOwn = same.value !== null && unitOf(same.unit) === own;
    if (rowIsOwn && !sameIsOwn) {
      // The one in the test's own unit leads; the other becomes how it was also printed.
      kept[kept.indexOf(same)] = { ...row, alsoAs: [...row.alsoAs, printedAs(same), ...same.alsoAs], sources: union(row.sources, same.sources) };
    } else {
      same.alsoAs.push(printedAs(row));
      same.sources = union(same.sources, row.sources);
    }
  }
  return kept;
}

/** How a reading reads as "also printed as": "34 mmol/mol", "class II", "Very High". */
function printedAs(reading: Reading): string {
  if (reading.value !== null) return `${reading.qualifier ?? ""}${reading.value}${reading.unit ? ` ${unitOf(reading.unit)}` : ""}`;
  const words = reading.text ?? "";
  return /^(0|I|II|III|IV|V|VI)$/.test(words) ? `class ${words}` : words;
}

function union(a: readonly string[], b: readonly string[]): string[] {
  return [...new Set([...a, ...b])];
}

function lineText(line: PdfLine): string {
  return line.map(([text]) => text).join(" ").replace(/\s+/g, " ").trim();
}
